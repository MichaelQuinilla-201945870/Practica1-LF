    private void calcularYMostrar(java.util.List<Token> tokens, java.util.List<ErrorLexico> errores, int totalLineas) {
        lblNumTokens.setText(String.valueOf(tokens.size()));
        lblNumLineas.setText(String.valueOf(totalLineas));
        lblNumErrores.setText(String.valueOf(errores.size()));

        javax.swing.table.DefaultTableModel modelo
                = new javax.swing.table.DefaultTableModel(new Object[]{"Tipo de token", "Cantidad"}, 0);

        for (TipoToken tipo : TipoToken.values()) {
            int contador = 0;
            for (Token t : tokens) {
                if (t.getTipo() == tipo) {
                    contador++;
                }
            }
            modelo.addRow(new Object[]{tipo, contador});
        }

        tablaFrecuencia.setModel(modelo);
        tablaFrecuencia.getColumnModel().getColumn(0).setCellRenderer(new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable tabla, Object valor,
                    boolean seleccionado, boolean foco, int fila, int columna) {
                java.awt.Component celda = super.getTableCellRendererComponent(tabla, valor, seleccionado, foco, fila, columna);
                celda.setForeground(colorParaTipo((TipoToken) valor));
                return celda;
            }
        });
    }

    private Color colorParaTipo(TipoToken tipo) {
        switch (tipo) {
            case DIRECTIVA:
                return new java.awt.Color(77, 182, 172);
            case PALABRA_RESERVADA:
                return new java.awt.Color(100, 160, 220);
            case COMANDO_IA:
                return new java.awt.Color(199, 125, 187);
            case CONECTOR:
                return new java.awt.Color(224, 164, 88);
            case LITERAL_CADENA:
                return new java.awt.Color(224, 108, 117);
            case LITERAL_ENTERO:
            case LITERAL_DECIMAL:
                return new java.awt.Color(152, 195, 121);
            default:
                return java.awt.Color.LIGHT_GRAY;
        }
    }

